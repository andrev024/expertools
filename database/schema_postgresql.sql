-- PostgreSQL schema matching the current multi-company MySQL schema.
-- Apply only to an empty target database.

CREATE TABLE ferreteria (
    id integer GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    slug varchar(80) NOT NULL,
    nombre_comercial varchar(150) NOT NULL,
    telefono varchar(60),
    direccion varchar(255),
    logo_key varchar(512),
    codigo_prefijo varchar(20) NOT NULL DEFAULT 'OT-A-',
    siguiente_consecutivo integer NOT NULL DEFAULT 600,
    creado_en timestamptz DEFAULT CURRENT_TIMESTAMP,
    CONSTRAINT uq_ferreteria_slug UNIQUE (slug)
);

CREATE TABLE usuario (
    id integer GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    ferreteria_id integer NOT NULL,
    nombre varchar(100) NOT NULL,
    email varchar(150) NOT NULL,
    password_hash varchar(255) NOT NULL,
    rol varchar(20) NOT NULL,
    creado_en timestamptz DEFAULT CURRENT_TIMESTAMP,
    CONSTRAINT email UNIQUE (email),
    CONSTRAINT ck_usuario_rol CHECK (rol IN ('recepcion', 'tecnico', 'admin')),
    CONSTRAINT fk_usuario_ferreteria FOREIGN KEY (ferreteria_id) REFERENCES ferreteria (id)
);

CREATE TABLE cliente (
    id integer GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    ferreteria_id integer NOT NULL,
    nombre varchar(150),
    telefono varchar(60),
    telefono_2 varchar(30),
    cedula varchar(20),
    empresa varchar(150),
    correo varchar(150),
    direccion varchar(255),
    creado_en timestamptz DEFAULT CURRENT_TIMESTAMP,
    CONSTRAINT fk_cliente_ferreteria FOREIGN KEY (ferreteria_id) REFERENCES ferreteria (id)
);

CREATE TABLE articulo (
    id integer GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    cliente_id integer NOT NULL,
    tipo varchar(100) NOT NULL,
    marca varchar(100),
    modelo varchar(100),
    serial varchar(100),
    creado_en timestamptz DEFAULT CURRENT_TIMESTAMP,
    CONSTRAINT articulo_ibfk_1 FOREIGN KEY (cliente_id) REFERENCES cliente (id)
);

CREATE TABLE orden_servicio (
    id integer GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    ferreteria_id integer NOT NULL,
    codigo_seguimiento varchar(20) NOT NULL,
    articulo_id integer NOT NULL,
    tipo varchar(20) NOT NULL DEFAULT 'reparacion',
    orden_original_id integer,
    tecnico_asignado_id integer,
    estado_actual varchar(50) NOT NULL DEFAULT 'recibido',
    ubicacion_actual varchar(150),
    intentos_contacto_cliente integer NOT NULL DEFAULT 0,
    observaciones text,
    fecha_ingreso timestamptz DEFAULT CURRENT_TIMESTAMP,
    fecha_entrega timestamptz,
    CONSTRAINT uq_orden_ferreteria_codigo UNIQUE (ferreteria_id, codigo_seguimiento),
    CONSTRAINT ck_orden_servicio_tipo CHECK (tipo IN ('reparacion', 'garantia')),
    CONSTRAINT fk_orden_ferreteria FOREIGN KEY (ferreteria_id) REFERENCES ferreteria (id),
    CONSTRAINT orden_servicio_ibfk_1 FOREIGN KEY (articulo_id) REFERENCES articulo (id),
    CONSTRAINT orden_servicio_ibfk_2 FOREIGN KEY (tecnico_asignado_id) REFERENCES usuario (id),
    CONSTRAINT orden_servicio_ibfk_3 FOREIGN KEY (orden_original_id) REFERENCES orden_servicio (id)
);

CREATE TABLE accesorio (
    id integer GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    articulo_id integer NOT NULL,
    nombre varchar(150) NOT NULL,
    descripcion varchar(255),
    creado_en timestamptz DEFAULT CURRENT_TIMESTAMP,
    CONSTRAINT accesorio_ibfk_1 FOREIGN KEY (articulo_id) REFERENCES articulo (id) ON DELETE CASCADE
);

CREATE TABLE cotizacion (
    id integer GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    orden_id integer NOT NULL,
    repuestos text,
    dictamen text,
    monto numeric(12,2) NOT NULL,
    abono numeric(12,2) NOT NULL DEFAULT 0.00,
    subtotal numeric(12,2),
    iva numeric(12,2) DEFAULT 0.00,
    canal_aprobacion varchar(20),
    estado varchar(20) NOT NULL DEFAULT 'pendiente',
    fecha_registro timestamptz DEFAULT CURRENT_TIMESTAMP,
    fecha_respuesta timestamptz,
    CONSTRAINT ck_cotizacion_canal CHECK (canal_aprobacion IS NULL OR canal_aprobacion IN ('presencial', 'whatsapp')),
    CONSTRAINT ck_cotizacion_estado CHECK (estado IN ('pendiente', 'aprobada', 'rechazada', 'sin_respuesta')),
    CONSTRAINT cotizacion_ibfk_1 FOREIGN KEY (orden_id) REFERENCES orden_servicio (id)
);

CREATE TABLE cotizacion_detalle (
    id integer GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    cotizacion_id integer NOT NULL,
    item_n integer,
    codigo varchar(50),
    cantidad numeric(10,2) NOT NULL DEFAULT 1.00,
    descripcion varchar(255) NOT NULL,
    precio_unitario numeric(12,2),
    precio_total numeric(12,2) NOT NULL,
    CONSTRAINT cotizacion_detalle_ibfk_1 FOREIGN KEY (cotizacion_id) REFERENCES cotizacion (id) ON DELETE CASCADE
);

CREATE TABLE historial_estado (
    id integer GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    orden_id integer NOT NULL,
    estado varchar(50) NOT NULL,
    comentario text,
    fecha timestamptz DEFAULT CURRENT_TIMESTAMP,
    usuario_id integer,
    CONSTRAINT historial_estado_ibfk_1 FOREIGN KEY (orden_id) REFERENCES orden_servicio (id),
    CONSTRAINT historial_estado_ibfk_2 FOREIGN KEY (usuario_id) REFERENCES usuario (id)
);

CREATE TABLE notificacion (
    id integer GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    orden_id integer NOT NULL,
    mensaje text NOT NULL,
    estado varchar(20) NOT NULL DEFAULT 'pendiente',
    fecha timestamptz DEFAULT CURRENT_TIMESTAMP,
    CONSTRAINT ck_notificacion_estado CHECK (estado IN ('pendiente', 'enviado', 'fallido')),
    CONSTRAINT notificacion_ibfk_1 FOREIGN KEY (orden_id) REFERENCES orden_servicio (id)
);

CREATE INDEX idx_usuario_ferreteria ON usuario (ferreteria_id);
CREATE INDEX idx_cliente_ferreteria ON cliente (ferreteria_id);
CREATE INDEX articulo_cliente_id_idx ON articulo (cliente_id);
CREATE INDEX idx_orden_ferreteria ON orden_servicio (ferreteria_id);
CREATE INDEX orden_servicio_articulo_id_idx ON orden_servicio (articulo_id);
CREATE INDEX orden_servicio_tecnico_asignado_id_idx ON orden_servicio (tecnico_asignado_id);
CREATE INDEX orden_servicio_orden_original_id_idx ON orden_servicio (orden_original_id);
CREATE INDEX accesorio_articulo_id_idx ON accesorio (articulo_id);
CREATE INDEX cotizacion_orden_id_idx ON cotizacion (orden_id);
CREATE INDEX cotizacion_detalle_cotizacion_id_idx ON cotizacion_detalle (cotizacion_id);
CREATE INDEX historial_estado_usuario_id_idx ON historial_estado (usuario_id);
CREATE INDEX idx_orden ON historial_estado (orden_id);
CREATE INDEX notificacion_orden_id_idx ON notificacion (orden_id);
